import {readFileSync,writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
const require=createRequire('/workspace/site/package.json');
const YAML=require('yaml');
const run=process.argv[2],phase=process.argv[3]??'prepublish';
if(!['prepublish','completed'].includes(phase))throw Error('Invalid state validation phase');
const read=p=>readFileSync(p),sha=b=>createHash('sha256').update(b).digest('hex');
const before=YAML.parse(read(run+'/state-before.yaml').toString());
const current=YAML.parse(read('BUILD_STATE.yaml').toString());
const buildId='rewrite-ch17-problem-first-content-20261002';
const strip=v=>({...v,updated_at:null,builds:v.builds.filter(b=>b.build_id!==buildId)});
if(JSON.stringify(strip(before))!==JSON.stringify(strip(current)))throw Error('Unrelated build, environment, active pointer or hold changed');
const old=before.builds.find(b=>b.build_id===buildId),build=current.builds.find(b=>b.build_id===buildId);
if(build.steps.length!==1||build.steps[0].id!==buildId)throw Error('Content step identity changed');
const step=build.steps[0],prior=old.steps[0];
if(JSON.stringify(prior.runs.slice(0,-1))!==JSON.stringify(step.runs.slice(0,-1)))throw Error('Historical run changed');
if(!read('DECISIONS.md').toString().startsWith(read(run+'/decisions-before.md').toString()))throw Error('Decision history rewritten');
const latest=step.runs.at(-1);
if(latest.run_id!==run.split('/').at(-1))throw Error('Wrong current run');
for(const item of latest.artifacts??[])if(sha(read(item.path))!==item.sha256)throw Error('Run artifact hash differs: '+item.path);
if(phase==='completed'){
  if(build.status!=='completed'||step.status!=='completed'||latest.status!=='succeeded'||!latest.finished_at)throw Error('Completion checkpoint incomplete');
  if(build.budget.limit!==4||build.budget.spent!==4)throw Error('Completion resource accounting differs');
  const proof={schemaVersion:1,result:'completion-ledger-verified',buildId,runId:latest.run_id,unrelatedBuilds:strip(current).builds.length,historicalRunsUnchanged:step.runs.length-1,artifactsChecked:latest.artifacts.length,stateSha256:sha(read('BUILD_STATE.yaml')),decisionsSha256:sha(read('DECISIONS.md')),limits:'Ledger/provenance/scope consistency only; publication quality comes from the independent exact verified records.'};
  const output='audits/2026-10-02-ch17-problem-first/verification/run04/state-completion-proof.json';
  writeFileSync(output,JSON.stringify(proof,null,2)+'\n',{flag:'wx'});
  console.log(JSON.stringify(proof));
}else console.log('Valid complete YAML; unrelated builds/holds, historical runs, decisions and current artifact hashes preserved.');
